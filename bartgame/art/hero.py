# the roll: the bloom ducks, then a ball of leaf and petal, then up
def roll_ball():
    c = Canvas(16, 16)
    ball(c, 8, 8.5, 7, 7, (8, 8, 9, 0xa, 0xa))
    for y in range(16):
        for x in range(16):
            dx, dy = x + 0.5 - 8, y + 0.5 - 8.5
            if dx * dx + dy * dy <= 3.2 * 3.2:
                c.set(x, y, 3 if dx + dy > -1 else 4)
    c.outline(1)
    return c.rows()


