def frame(head, body):
    """two clear rows, the head (14 rows), the body (16 rows): the feet
    sit on the frame's bottom edge, which is the actor's y"""
    assert len(head) == 14 and len(body) == 16, (len(head), len(body))
    return blank(16, 2) + head + body


def bob(rows, dy):
    """lower the whole figure by dy (walk bounce), keeping the frame size"""
    return shift(rows, 0, dy)


