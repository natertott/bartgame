def puff(r, tone):
    c = Canvas(16, 16)
    ball(c, 8, 8, r, r, (0xc, 0xc, 0xd, 0xe, 8))
    c.outline(1)
    return c.rows()


def burst(r, core, rim):
    """a bomb blast: a bright core, a ring, a jagged edge"""
    c = Canvas(16, 16)
    for y in range(16):
        for x in range(16):
            dx, dy = x + 0.5 - 8, y + 0.5 - 8
            d = (dx * dx + dy * dy) ** 0.5
            jag = 0.8 if (x + y) % 3 == 0 else 0
            if d < r * 0.45:
                c.set(x, y, core)
            elif d < r * 0.8:
                c.set(x, y, 7)
            elif d < r + jag:
                c.set(x, y, rim)
    c.outline(1)
    return c.rows()


