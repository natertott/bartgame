from px import L, Canvas, ball, compose, shift, blank, remap  # noqa: F401


def seed_pod(cx, cy, rx, ry, fuse=True):
    """A blightseed: a violet pod with a bright seam, a fuse and a spark."""
    c = Canvas(16, 16)
    ball(c, cx, cy, rx, ry, (9, 9, 0xa, 0xb, 8))
    for y in range(int(cy - ry) + 1, int(cy + ry)):
        if c.get(int(cx), y) >= 0:
            c.set(int(cx), y, 9)
    c.outline(1)
    if fuse:
        x, y = int(cx), int(cy - ry) - 1
        c.set(x, y, 0xd); c.set(x + 1, y - 1, 0xd); c.set(x + 2, y - 2, 0xc)
        c.set(x + 3, y - 3, 7); c.set(x + 3, y - 2, 8); c.set(x + 4, y - 3, 7); c.set(x + 3, y - 4, 7); c.set(x + 2, y - 3, 7)
    return c.rows()


