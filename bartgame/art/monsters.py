# ------------------------------------------------------------- slime --
# A gloom slime: a dome of teal jelly over a violet shadow, two dark eyes
# with a glint, a gleam on its crown.
def slime(rx, ry, cy, eye_dx, eye_y):
    c = Canvas(16, 16)
    ball(c, 8, cy, rx, ry, (2, 0xc, 0xd, 0xe, 0xf))
    c.outline(1)
    for ex in (8 - eye_dx - 1, 8 + eye_dx):
        c.set(ex, eye_y, 1); c.set(ex + 1, eye_y, 1)
        c.set(ex, eye_y + 1, 1); c.set(ex + 1, eye_y + 1, 1)
        c.set(ex, eye_y, 0xf)
    return c.rows()


