# -------------------------------------------------------------- boss --
# The Blight Heart: a swollen heart of raw flesh, veined violet, with a
# single sick eye, blight roots growing out of its top, 32x32.
def heart(scale, hurt=False):
    c = Canvas(32, 32)
    r = 8.2 * scale
    cy = 12 + (1 - scale) * 4
    tones = (7, 8, 9, 0xa, 0xb)
    ball(c, 10.5, cy, r, r * 0.95, tones)
    ball(c, 21.5, cy, r, r * 0.95, tones)
    # the lower lobe to the point
    top = int(cy + 2)
    tip = int(cy + 16 * scale)
    for y in range(top, tip + 1):
        t = (y - top) / float(tip - top)
        half = (13.5 * scale) * (1 - t) + 0.6
        for x in range(32):
            dx = x + 0.5 - 16
            if abs(dx) <= half:
                col = 8 if dx > half - 2.5 or y > tip - 3 else 9 if dx > -half * 0.3 else 0xa
                if c.get(x, y) < 0 or y > top + 1:
                    c.set(x, y, col)
    # veins
    for (x0, y0, x1, y1) in ((6, 8, 9, 16), (24, 7, 21, 15), (13, 18, 15, 24), (19, 17, 18, 23), (9, 15, 12, 21)):
        n = max(abs(x1 - x0), abs(y1 - y0))
        for i in range(n + 1):
            x = x0 + (x1 - x0) * i // n
            y = y0 + (y1 - y0) * i // n
            if c.get(x, y) >= 0:
                c.set(x, y, 0xc if i % 3 else 0xd)
    # the eye: a sick yellow orb with a slit pupil
    ex, ey = 16, int(cy + 4)
    for y in range(ey - 3, ey + 4):
        for x in range(ex - 5, ex + 5):
            dx, dy = (x + 0.5 - ex) / 5.0, (y + 0.5 - ey) / 3.5
            if dx * dx + dy * dy <= 1:
                c.set(x, y, 6 if dx * dx + dy * dy < 0.7 else 5)
    for y in range(ey - 2, ey + 3):
        c.set(ex - 1, y, 1)
        c.set(ex, y, 1)
    c.set(ex - 2, ey - 2, 0xf); c.set(ex - 3, ey - 1, 0xf)
    c.outline(1)
    # blight roots growing from the top lobes
    roots = [(8, int(cy - r) + 1, -1), (12, int(cy - r) - 1, 0), (20, int(cy - r) - 1, 0), (24, int(cy - r) + 1, 1)]
    for (x, y, lean) in roots:
        for i in range(7):
            xx = x + (lean * i) // 2 + (1 if i % 3 == 2 else 0)
            yy = y - i
            c.set(xx, yy, 4 if i < 4 else 5)
            c.set(xx - 1, yy, 3)
            if i == 3:
                c.set(xx - 2 - lean, yy, 4); c.set(xx - 3 - lean, yy - 1, 5)
            if i == 6:
                c.set(xx + 1, yy - 1, 5)
    c.outline(1)
    rows = c.rows()
    if hurt:
        rows = remap(rows, {'7': 'e', '8': 'e', '9': 'f', 'a': 'f', 'b': 'f', 'c': 'e', 'd': 'f'})
    return rows


