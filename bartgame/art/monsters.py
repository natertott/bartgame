    ball(c, 13, 8, 1.8, 2.6, (2, 2, 3, 3, 3), gleam=False)
    c.outline(1)
    c.set(13, 7, 8); c.set(13, 10, 8)
    c.set(12, 7, 7); c.set(12, 10, 7)
    legs = [((5, 3), (4, 2)), ((8, 3), (8, 2)), ((11, 3), (12, 2))] if phase == 0 else \
           [((4, 3), (3, 2)), ((7, 3), (7, 2)), ((10, 3), (11, 2))]
    for (ax, ay), (bx, by) in legs:
        for (x, y) in ((ax, ay), (bx, by), (ax, 16 - ay), (bx, 16 - by)):
            c.set(x, y, 1)
    c.set(14, 5, 1); c.set(15, 4, 1); c.set(14, 11, 1); c.set(15, 12, 1)
    return c.rows()


