# eight-pixel dots for the overview: outlined discs
def dot(col):
    return L({}, '''
        ..1111..
        .1%s%s%s%s1.
        1%s%s%s%s%s%s1
        1%s%s%s%s%s%s1
        1%s%s%s%s%s%s1
        1%s%s%s%s%s%s1
        .1%s%s%s%s1.
        ..1111..
    ''' % tuple([col] * 32))


DOTS = {'here': dot('9'), 'door': dot('d'), 'folk': dot('a'), 'quest': dot('5'), 'relic': dot('e')}
for k in DOTS:
    DOTS[k][2] = DOTS[k][2][:2] + '6' + DOTS[k][2][3:] if k == 'quest' else DOTS[k][2]


# the overview cursor: a gold frame round one cell, 32 by 24
def cursor():
    c = Canvas(32, 32)
    for x in range(32):
        for y in (0, 1, 22, 23):
            c.set(x, y, 5)
    for y in range(24):
        for x in (0, 1, 30, 31):
            c.set(x, y, 5)
    for (x, y) in ((0, 0), (31, 0), (0, 23), (31, 23)):
        c.set(x, y, 6)
    for x in range(4, 28):
        c.set(x, 0, 6 if x % 2 else 5)
        c.set(x, 23, 6 if x % 2 else 5)
    return c.rows()


CURSOR = {'cell': cursor()}
