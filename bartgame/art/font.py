def render():
    glyphs = []
    for code in range(32, 127):
        rows = GLYPHS[chr(code)]
        g = [[0] * 8 for _ in range(8)]
        for y, r in enumerate(rows):
            for x, ch in enumerate(r):
                if ch == '#':
                    g[y][x + 1] = 1
        for y in range(8):
            for x in range(8):
                if g[y][x] == 1 and y + 1 < 8 and x + 1 < 8 and g[y + 1][x + 1] == 0:
                    g[y + 1][x + 1] = 2
        glyphs.append(g)
    return glyphs


