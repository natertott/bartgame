    c=Canvas(16,16)
    c.rect(4,4,10,12,1);c.rect(5,5,9,11,color);line(c,5,5,9,5,12)
    if shape==0:c.rect(9,5,12,7,color);c.rect(7,9,10,10,1)
    elif shape==1:c.rect(2,5,5,7,color);c.rect(8,8,11,10,1)
    else:c.rect(9,8,12,10,color);c.rect(7,5,10,7,1)
    line(c,5,11,9,11,8)
