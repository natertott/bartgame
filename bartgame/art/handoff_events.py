def torch(lit):
    c=Canvas(16,16)
    c.rect(6,7,9,13,1);c.rect(7,7,8,12,9);line(c,4,13,11,13,8);line(c,3,14,12,14,1)
    line(c,4,7,11,7,10);line(c,3,6,12,6,1)
    if lit:
        for x,y in [(7,1),(6,2),(7,2),(6,3),(7,3),(8,3),(5,4),(6,4),(7,4),(8,4),(9,4),(6,5),(7,5),(8,5)]:c.set(x,y,10 if x>7 else 12)
