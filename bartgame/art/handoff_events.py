from px import Canvas, L, hflip, compose, blank, remap

def line(c,x0,y0,x1,y1,ink):
    if x0==x1:c.vline(x0,min(y0,y1),max(y0,y1),ink)
    elif y0==y1:c.hline(min(x0,x1),max(x0,x1),y0,ink)
    else:raise ValueError("Only deliberate horizontal/vertical clusters")

def image(text):
    r=L({},text)
    assert len(r)==16 and all(len(s)==16 for s in r)
    return r

