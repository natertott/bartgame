def watcher(face):
    c=Canvas(16,16)
    c.rect(4,3,11,13,1);c.rect(5,4,10,11,3);line(c,5,4,10,4,10);line(c,3,13,12,13,8)
    if face in (0,2):
        yy=4 if face==0 else 9;line(c,6,yy,9,yy,15);c.set(7,yy,12)
    else:
        xx=9 if face==1 else 5;line(c,xx,6,xx,8,15);c.set(xx,6,12)
    return c.rows()
