def block(axis):
    c=Canvas(16,16)
    c.rect(1,1,14,14,1);c.rect(2,2,13,13,8);c.rect(3,3,12,11,9)
    line(c,3,3,12,3,11);line(c,3,3,3,10,10);line(c,3,12,12,12,7)
    col=14 if axis==1 else 15 if axis==2 else 11
    if axis==1:
        line(c,4,7,11,7,col);line(c,4,8,11,8,col)
        for x,y in [(4,6),(4,9),(11,6),(11,9),(3,7),(3,8),(12,7),(12,8)]:c.set(x,y,col)
    elif axis==2:
        line(c,7,4,7,11,col);line(c,8,4,8,11,col)
        for x,y in [(6,4),(9,4),(6,11),(9,11),(7,3),(8,3),(7,12),(8,12)]:c.set(x,y,col)
    else:
        c.rect(6,6,9,9,1);c.rect(7,7,8,8,col)
    return c.rows()
