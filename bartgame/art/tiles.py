"""BARTGAME metatiles: 16x16 tiles with a behavior type and collision.

Art is rows of 16 hex digits. Most floor variants are generated
(speckled moss, flagstones) from a seed; the landmark tiles are drawn.

Palette 'forest':  0 black, 1-5 moss (dark to light), 6-9 bark, A-C blight
                   violet, D-F rot yellow-green.
Palette 'forest2': 0 black, 1-5 stone, 6-9 water, A-D gold, E bone, F violet.
Palette 'sewer':   0 black, 1-5 wet stone, 6-8 slime, 9-B water, C-D rust,
                   E-F gold.
"""
import random

TYPES = ['FLOOR', 'SOLID', 'PIT', 'WATER', 'LEDGE_N', 'LEDGE_E', 'LEDGE_S', 'LEDGE_W',
         'THORN', 'CRACK', 'WEB', 'DOOR', 'DOOR_OPEN', 'TORCH', 'TORCH_LIT', 'SLOW', 'HURT',
         'EXIT', 'CHEST', 'CHEST_OPEN', 'SWITCH', 'STAIRS']

SOLID_TYPES = {'SOLID', 'THORN', 'CRACK', 'WEB', 'DOOR', 'TORCH', 'TORCH_LIT', 'CHEST', 'CHEST_OPEN'}


def default_coll(t):
    return 15 if t in SOLID_TYPES else 0


def speckle(seed, base, spots, w=16, h=16):
    """A flat tile of `base` with random single-pixel spots.
    spots: list of (hexdigit, count)."""
    rnd = random.Random(seed)
    g = [[base] * w for _ in range(h)]
    for col, n in spots:
        for _ in range(n):
            g[rnd.randrange(h)][rnd.randrange(w)] = col
    return [''.join('%x' % c for c in row) for row in g]


def clumps(seed, base, col, n, size=2, w=16, h=16):
    rnd = random.Random(seed)
    g = [[base] * w for _ in range(h)]
    for _ in range(n):
        x, y = rnd.randrange(w), rnd.randrange(h)
        for dy in range(size):
            for dx in range(size):
                if rnd.random() < 0.7:
                    g[(y + dy) % h][(x + dx) % w] = col
    return [''.join('%x' % c for c in row) for row in g]


def overlay(base_rows, top_rows):
    """Draw top_rows over base_rows where top is not '.'."""
    out = []
    for b, t in zip(base_rows, top_rows):
        out.append(''.join(tc if tc != '.' else bc for bc, tc in zip(b, t)))
    return out


def hflip(rows):
    return [r[::-1] for r in rows]


def vflip(rows):
    return rows[::-1]


def A(s):
    """Multi-line string to rows, ignoring blank lines and indentation."""
    return [ln.strip() for ln in s.strip('\n').splitlines() if ln.strip()]


METATILES = []


def mt(name, pal, type_, art=None, frames=None, coll=None, anim_speed=8):
    d = {'name': name, 'pal': pal, 'type': type_}
    if frames:
        d['frames'] = frames
    else:
        d['art'] = art
    if coll is not None:
        d['coll'] = coll
    if anim_speed:
        d['anim_speed'] = anim_speed
    METATILES.append(d)


