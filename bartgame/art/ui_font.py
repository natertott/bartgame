EXTRA={'\x7f':['.###.','#...#','#.#.#','#...#','.###.'],
       '\x80':['##.##','#####','#####','.###.','..#..']}
for ch,rs in list(GLYPHS.items())+list(EXTRA.items()):
    assert len(rs)<=HEIGHT,(ch,rs)
    assert all(len(r)==len(rs[0]) for r in rs),(ch,rs)
assert all(chr(n) in GLYPHS for n in range(32,127))

def glyph(ch):
    rs=GLYPHS.get(ch) or EXTRA.get(ch) or GLYPHS['?'];w=len(rs[0])
    return w,rs+['.'*w]*(HEIGHT-len(rs))

def width(s,space=3):
    return sum(space if ch==' ' else glyph(ch)[0]+(i+1<len(s)) for i,ch in enumerate(s) if ord(ch)>=32)
