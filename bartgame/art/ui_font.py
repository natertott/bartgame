# the UI's own marks, after '~' (127 up): a gilt coin, a heart, the
# buttons as a reader sees them on the box
EXTRA = {
    '\x7f': ['.###.', '#.#.#', '##.##', '#.#.#', '.###.'],                       # a coin
    '\x80': ['##.##', '#####', '#####', '.###.', '..#..'],                       # a heart
}

for _c, _rows in list(GLYPHS.items()) + list(EXTRA.items()):
    assert len(_rows) <= HEIGHT, repr(_c)
    _w = len(_rows[0])
    assert all(len(r) == _w for r in _rows), ('ragged glyph', repr(_c))
for _code in range(32, 127):
    assert chr(_code) in GLYPHS, ('no glyph', chr(_code))


def glyph(ch):
    rows = GLYPHS.get(ch) or EXTRA.get(ch) or GLYPHS['?']
    w = len(rows[0])
    return w, rows + ['.' * w] * (HEIGHT - len(rows))


def width(s, space=3):
    """a string's width in pixels, as the engine sets it"""
    n = 0
    for i, ch in enumerate(s):
        if ch == ' ':
            n += space
        elif ord(ch) >= 32:
            n += glyph(ch)[0] + (1 if i + 1 < len(s) else 0)
    return n
